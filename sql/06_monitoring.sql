SELECT
    NAME,
    STATE,
    SCHEDULED_TIME,
    QUERY_START_TIME,
    COMPLETED_TIME,
    ERROR_MESSAGE
FROM TABLE(
    TRAINING_MEDALLION_DB.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START =>
            DATEADD('DAY', -2, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    )
)
WHERE NAME IN ('SILVER_DAILY_TASK', 'GOLD_DAILY_TASK')
ORDER BY SCHEDULED_TIME DESC;
