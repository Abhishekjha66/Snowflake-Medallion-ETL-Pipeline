-- Set up the Snowflake environment for the Medallion ETL pipeline

USE ROLE ACCOUNTADMIN;

-- Create the project database
CREATE DATABASE IF NOT EXISTS TRAINING_MEDALLION_DB;

-- Create Medallion architecture schemas
CREATE SCHEMA IF NOT EXISTS TRAINING_MEDALLION_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS TRAINING_MEDALLION_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS TRAINING_MEDALLION_DB.GOLD;

-- Create the virtual warehouse
CREATE WAREHOUSE IF NOT EXISTS SNOWFLAKE_LEARNING_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 300
    AUTO_RESUME = TRUE;

-- Set the active project context
USE DATABASE TRAINING_MEDALLION_DB;
USE SCHEMA BRONZE;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
