-- Create scheduled tasks for the Silver and Gold ETL pipeline

USE DATABASE TRAINING_MEDALLION_DB;
USE SCHEMA SILVER;

-- Task 1: Refresh Silver data daily at 8:00 AM IST
CREATE OR REPLACE TASK SILVER_DAILY_TASK
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    SCHEDULE = 'USING CRON 0 8 * * * Asia/Kolkata'
AS
    CREATE OR REPLACE TABLE TRAINING_MEDALLION_DB.SILVER.CLEAN_SALES AS
    SELECT
        SALE_ID,
        TRIM(CUSTOMER_NAME) AS CUSTOMER_NAME,
        TRIM(PRODUCT) AS PRODUCT,
        AMOUNT,
        SALE_DATE
    FROM TRAINING_MEDALLION_DB.BRONZE.RAW_SALES
    WHERE SALE_ID IS NOT NULL
      AND CUSTOMER_NAME IS NOT NULL
      AND PRODUCT IS NOT NULL
      AND AMOUNT > 0
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SALE_ID
        ORDER BY SALE_DATE DESC
    ) = 1;

-- Task 2: Refresh Gold after Silver completes
CREATE OR REPLACE TASK GOLD_DAILY_TASK
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    AFTER SILVER_DAILY_TASK
AS
    CREATE OR REPLACE TABLE TRAINING_MEDALLION_DB.GOLD.SALES_SUMMARY AS
    SELECT
        PRODUCT,
        COUNT(*) AS TOTAL_SALES,
        SUM(AMOUNT) AS TOTAL_REVENUE,
        AVG(AMOUNT) AS AVERAGE_SALE_AMOUNT
    FROM TRAINING_MEDALLION_DB.SILVER.CLEAN_SALES
    GROUP BY PRODUCT;

-- Resume the child task first, then the root task
ALTER TASK GOLD_DAILY_TASK RESUME;
ALTER TASK SILVER_DAILY_TASK RESUME;
