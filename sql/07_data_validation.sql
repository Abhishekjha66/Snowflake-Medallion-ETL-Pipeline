-- Validate data across Bronze, Silver, and Gold layers

-- 1. Check Bronze record count
SELECT
    'BRONZE' AS LAYER,
    COUNT(*) AS TOTAL_RECORDS
FROM TRAINING_MEDALLION_DB.BRONZE.RAW_SALES;

-- 2. Check Silver record count
SELECT
    'SILVER' AS LAYER,
    COUNT(*) AS TOTAL_RECORDS
FROM TRAINING_MEDALLION_DB.SILVER.CLEAN_SALES;

-- 3. Check Gold record count
SELECT
    'GOLD' AS LAYER,
    COUNT(*) AS TOTAL_RECORDS
FROM TRAINING_MEDALLION_DB.GOLD.SALES_SUMMARY;

-- 4. Check for invalid records in Silver
SELECT *
FROM TRAINING_MEDALLION_DB.SILVER.CLEAN_SALES
WHERE SALE_ID IS NULL
   OR CUSTOMER_NAME IS NULL
   OR PRODUCT IS NULL
   OR AMOUNT <= 0;

-- 5. Verify Gold sales summary
SELECT
    PRODUCT,
    TOTAL_SALES,
    TOTAL_REVENUE,
    AVERAGE_SALE_AMOUNT
FROM TRAINING_MEDALLION_DB.GOLD.SALES_SUMMARY
ORDER BY PRODUCT;
